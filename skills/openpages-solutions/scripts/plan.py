def package_md(spec) -> str:
    """Ordered deploy runbook. Hybrid: generated/derived ObjectManager loaders for structure (regenerated against
    the TARGET's own dumps), Configuration Packaging for solution-owned config, and recorded manual edits for
    shared IBM configuration."""
    s = spec["solution"]
    key, k = s["key"], s["key"].lower()
    types = [t["name"] for t in spec.get("object_types", []) or []]
    exts = spec.get("type_extensions", []) or []
    rels = spec.get("relationships", []) or []
    wchg = spec.get("workflow_changes", []) or []
    qns = spec.get("questionnaires", []) or []
    groups = sorted({st["assignee"].split(":", 1)[1] for w in spec.get("workflows", []) for st in w.get("stages", [])
                     if str(st.get("assignee", "")).startswith("group:")})
    L = [f"# Package & deploy runbook: {s['name']} v{s['version']}", "",
         f"Target must run the **same OpenPages version and patch level** as dev ({s.get('target_version', '?')}).",
         "Policy: no SQL/DDL; never drop or re-create Db2 tables or the reporting schema.", "",
         "## What goes how", "",
         "| Layer | Items | Mechanism | Why |", "|---|---|---|---|",
         f"| 1 Object types | {', '.join(types)} | derived loaders `build/{key}/types/*-op-config.xml` (ObjectManager) | no UI to create types in 9.2.x |"]
    fg = [g["name"] for t in spec.get("object_types", []) for g in t.get("field_groups", [])] + \
         [f"{g['name']} (on {e['type']})" for e in exts for g in e.get("field_groups", [])]
    L.append(f"| 2 Fields + profile inclusion | {', '.join(fg)}; profiles {', '.join(spec.get('profiles', []) or [])} | "
             f"`gen_fields.py` loader, **regenerated against the target's dump** | merges into the shared profile instead of replacing it |")
    rel_items = [f"{p}->{t['name']}" for t in spec.get("object_types", []) for p in
                 [x["type"] if isinstance(x, dict) else x for x in t.get("parents", [])]] + [f"{r['parent']}->{r['child']}" for r in rels]
