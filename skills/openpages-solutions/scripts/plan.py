def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["build", "package", "questionnaire"])
    ap.add_argument("spec")
    args = ap.parse_args(argv)
    spec = load_spec(args.spec)
    d = outdir(spec)
    if args.what == "questionnaire":
        if not spec.get("questionnaires"):
            raise SystemExit("spec has no questionnaires section")
        import re as _re
        for qn in spec["questionnaires"]:
            f = d / f"QUESTIONNAIRE-{_re.sub(r'[^A-Za-z0-9]+', '-', qn['name']).strip('-')}.md"
            f.write_text(questionnaire_md(spec, qn))
            print(f"-> {f}")
        return
    if args.what == "build":
        (d / "BUILD.md").write_text(build_md(spec))
        print(f"-> {d / 'BUILD.md'}")
    else:
        (d / "PACKAGE.md").write_text(package_md(spec))
        (d / "ObjectManagerExportFilters.xml").write_text(filters_xml(spec))
        (d / "ObjectManager.properties.snippet").write_text(PROPS)
        print(f"-> {d / 'PACKAGE.md'}\n-> {d / 'ObjectManagerExportFilters.xml'}\n-> {d / 'ObjectManager.properties.snippet'}")


if __name__ == "__main__":
    main()
