def _conds(sw):
    if not sw:
        return ""
    parts = []
    for i, c in enumerate(sw.get("conditions", []), 1):
        if "question" in c:
            parts.append(f"({i}) {c['question']} in {c.get('in')}")
        else:
            parts.append(f"({i}) {c['field']} {c.get('op', 'equal')} {c.get('value', '')}".rstrip())
    return "; ".join(parts) + (f"; logic: {sw['logic']}" if sw.get("logic") else "")


