def filters_xml(spec) -> str:
    key = spec["solution"]["key"]
    types = [t["name"] for t in spec.get("object_types", [])]
    groups = [g["name"] for t in spec.get("object_types", []) for g in t.get("field_groups", [])]
    X = ['<?xml version="1.0" encoding="UTF-8"?>',
         f"<!-- ObjectManager export filters for {spec['solution']['name']} ({key}). Place next to ObjectManager.sh -->",
         "<!-- objectProfiles/responsiveViews wrappers are from the 9.2.x docs examples; contentTypes/bundleTypes/queryDefinitions",
         "     follow the same loader convention - confirm against ObjectManagerExportFilters-Example.xml in your tools client bin/. -->",
         '<openpagesConfigurationBOM xmlFormatVersion="1.0">']
    X += ["  <contentTypes>"] + [f"    <contentType name={quoteattr(n)}/>" for n in types] + ["  </contentTypes>"]
    X += ["  <bundleTypes>"] + [f"    <bundleType name={quoteattr(n)}/>" for n in groups] + ["  </bundleTypes>"]
    if spec.get("profiles"):
        X += ["  <objectProfiles>"] + [f"    <objectProfile name={quoteattr(p)}/>" for p in spec["profiles"]] + ["  </objectProfiles>"]
    if spec.get("views"):
        X += ["  <responsiveViews>"] + [f"    <responsiveView name={quoteattr(v['name'])}/>" for v in spec["views"]] + ["  </responsiveViews>"]
    if spec.get("filters"):
        X += ["  <queryDefinitions>"] + [f"    <queryDefinition name={quoteattr(f['name'])}/>" for f in spec["filters"]] + ["  </queryDefinitions>"]
    X.append("</openpagesConfigurationBOM>")
    return "\n".join(X)


